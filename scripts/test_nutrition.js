'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const c=vm.createContext({Object,Array,String,Set,e:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;')});
vm.runInContext(fs.readFileSync('web/nutrition.js','utf8'),c);
assert.equal(c.nutritionSpecLabel({category_group:'nutrition'}),'口味与包装规格');
assert.equal(c.nutritionSpecLabel({category:'sunscreen'}),'容量规格');
assert.equal(c.nutritionSpecLabel({category_group:'clothing'}),'尺码');
assert.equal(c.nonFitProduct({category:'sunscreen'}),true);
assert.equal(c.nonFitProduct({category_group:'nutrition'}),true);
assert.equal(c.nonFitProduct({category_group:'clothing'}),false);
assert.equal(c.nutritionDetailMarkup({category_group:'clothing'}),'');
const html=c.nutritionDetailMarkup({category_group:'nutrition',offers:[{offer:{source_name:'Maurten France',name:'Gel 100',source_code:'maurten',url:'https://www.maurten.com/fr/products/gel-100-box'}}]});
assert.match(html,/<details class="nutrition-product-reference">/);
assert.match(html,/Maurten/);assert.doesNotMatch(html,/SiS| open|<a |¥|data-purchase/);
assert.match(html,/https:\/\/www.maurten.com\/fr\/products\/gel-100-box/);
assert.doesNotMatch(html,/box-us/);
assert.doesNotMatch(c.nutritionDetailMarkup({category_group:'nutrition',offers:[{offer:{source_name:'<script>',name:'Unsafe',url:'<a>'}}]}),/<script>|<a>/);
assert.doesNotMatch(fs.readFileSync('web/gallery.js','utf8'),/renderNutritionReferences/);
console.log('PASS nutrition detail evidence: collapsed, offer-bound source evidence, no outbound bypass, nutrition/sunscreen labels and fit scope.');
